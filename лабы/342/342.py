import numpy as np
import matplotlib.pyplot as plt
from scipy.stats import linregress

# --- Исходные данные из твоего сообщения ---
T_bath = np.array([14.12, 16.00, 18.02, 20.03, 22.00, 24.00, 26.01, 28.00, 30.00, 32.00, 34.00, 36.00, 38.00, 40.00])
tau = np.array([10.780, 10.718, 10.544, 10.218, 9.922, 9.600, 9.426, 9.358, 9.3036, 9.272, 9.243, 9.226, 9.211, 9.199])
U = np.array([-0.001, -0.009, -0.006, -0.0027, -0.006, -0.0088, -0.003, -0.0088, -0.078, -0.0083, -0.0059, -0.0078, -0.0076, -0.0089])

# Параметры установки
tau0 = 9.045  # мкс
k_thermo = 24.0  # град/мВ

# --- Обработка (п. 6) ---
# 1. Температура образца: T = T_термостата + dT (dT = U * k)
# Знак "+" по условию, если температура образца выше жидкости.
T_sample = T_bath + U * k_thermo

# 2. Расчет величины 1 / (tau^2 - tau0^2)
# Переводим мкс в секунды для удобства? Нет, для графика сойдет и так, 
# но для физики лучше в СИ. Оставим в мкс^2, так как это относительные величины.
y_vals = 1.0 / (tau**2 - tau0**2)

# --- Построение графика ---
plt.figure(figsize=(10, 6))
plt.plot(T_sample, y_vals, 'o', label='Экспериментальные точки')

# --- Аппроксимация (линейный участок) ---
# Берем точки начиная с 24°C (индекс 5) до конца, так как ниже 20°C 
# начинается ферромагнитная фаза, где закон Кюри-Вейсса не работает.
start_idx = 5 
res = linregress(T_sample[start_idx:], y_vals[start_idx:])
slope, intercept, r_value, p_value, std_err = res

# Строим аппроксимирующую прямую
x_fit = np.linspace(18, 42, 100)
y_fit = slope * x_fit + intercept
plt.plot(x_fit, y_fit, 'r--', label=f'Линейная аппроксимация\n(наклон {slope:.2e})')

# Находим точку пересечения с осью X (Theta_p)
# 0 = slope * T + intercept => T = -intercept / slope
theta_p = -intercept / slope

plt.axvline(x=theta_p, color='g', linestyle=':', label=f'Парамагнитная точка Кюри: {theta_p:.2f} °C')
plt.axhline(y=0, color='k', linewidth=0.8)

plt.xlabel('Температура образца T, °C')
plt.ylabel('1 / (τ² - τ₀²), мкс⁻²')
plt.title('Закон Кюри-Вейсса для гадолиния')
plt.legend()
plt.grid(True)
plt.show()

# --- Вывод результатов ---
print(f"Уравнение прямой: y = {slope:.4e} * T + {intercept:.4e}")
print(f"Парамагнитная точка Кюри (Theta_p): {theta_p:.2f} °C")
print(f"Коэффициент корреляции R^2: {r_value**2:.4f}")

# Оценка ферромагнитной точки Кюри (Theta_K)
# Где график отклоняется от прямой.
# Визуально: посмотрим на первые 4-5 точек (до 24°C).
# Если принять, что прямая справедлива для T > Theta_p, то отклонение вниз 
# начинается примерно при T = 20-22 °C.
# Точнее можно оценить, сравнив экспериментальное значение с предсказанным по прямой.
y_pred = slope * T_sample + intercept
deviation = y_pred - y_vals

# Выведем таблицу для наглядности
print("\nТаблица значений:")
print(f"{'T_bath':<10} | {'T_sample':<10} | {'tau':<10} | {'y_exp':<10} | {'y_fit':<10}")
for i in range(len(T_sample)):
    print(f"{T_bath[i]:<10.2f} | {T_sample[i]:<10.2f} | {tau[i]:<10.4f} | {y_vals[i]:<10.2e} | {y_pred[i]:<10.2e}")